package main

import "fmt"

func main() {

	fmt.Println(1) // for integer value

	fmt.Println(true) // for boolean value

	fmt.Println("Hello World!") // for string value

	fmt.Println(3.14) // for float value

	fmt.Println(7.0 / 3.0) // for float divide value

	fmt.Printf("%2.2f\n", 31212.14456) // for float value with 2 decimal points
}
